"""Review sheet and guide of the deduplication stages (D011).

The sheet is a CSV in UTF-8 with BOM, separated by ';', one row per case member:
`case;member;group;max_similarity;questions;text`. Only `group` is filled in by hand.
The guide is Markdown generated from the cases; it holds no manual work.
"""

import csv
import re
from difflib import SequenceMatcher
from pathlib import Path

from opox.dedup.core import Case, Row, Stage, canonical
from opox.models.questions import Question

COLUMNS = ["case", "member", "group", "max_similarity", "questions", "text"]
_LETTERS = "abcd"


def member_letter(i: int) -> str:
    """A, B... Z, AA, AB..."""
    letters = ""
    i += 1
    while i:
        i, r = divmod(i - 1, 26)
        letters = chr(ord("A") + r) + letters
    return letters


def case_ids(cases: list[Case]) -> list[str]:
    width = max(2, len(str(len(cases))))
    return [f"C{n:0{width}d}" for n in range(1, len(cases) + 1)]


def read_sheet(path: Path) -> tuple[list[Row], list[str]]:
    """Rows with stripped values, or errors if the columns are wrong."""
    with path.open(encoding="utf-8-sig", newline="") as f:
        reader = csv.DictReader(f, delimiter=";")
        if reader.fieldnames != COLUMNS:
            return [], [f"{path}: columns must be {';'.join(COLUMNS)}"]
        return [
            Row(
                line=reader.line_num,
                case=(r["case"] or "").strip(),
                member=(r["member"] or "").strip(),
                group=(r["group"] or "").strip(),
                questions=(r["questions"] or "").strip(),
            )
            for r in reader
        ], []


def sheet_rows(cases: list[Case], stage: Stage, labels: dict[str, str]) -> list[list[str]]:
    """Rows for the cases, with the labels already decided for each member."""
    rows = []
    for case_id, case in zip(case_ids(cases), cases, strict=True):
        for i, m in enumerate(case.members):
            rows.append(
                [
                    case_id,
                    member_letter(i),
                    labels.get(m.ids, ""),
                    f"{case.best(i):.0f}",
                    m.ids,
                    _one_line(stage.text(canonical(m.questions))),
                ]
            )
    return rows


def write_sheet(path: Path, rows: list[list[str]]) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    with path.open("w", encoding="utf-8-sig", newline="") as f:
        writer = csv.writer(f, delimiter=";")
        writer.writerow(COLUMNS)
        writer.writerows(rows)


# --- Guide -------------------------------------------------------------------------------


def _one_line(s: str) -> str:
    return re.sub(r"\s+", " ", s).strip()


def _md(s: str) -> str:
    return re.sub(r"([\\`*_~\[\]<>|#])", r"\\\1", s)


def word_diff(a: str, b: str) -> str:
    """Words of b against a: removed as ~~x~~, added as **x**."""
    wa, wb = _one_line(a).split(), _one_line(b).split()
    out = []
    for op, i1, i2, j1, j2 in SequenceMatcher(a=wa, b=wb, autojunk=False).get_opcodes():
        if op in ("delete", "replace"):
            out.append(f"~~{_md(' '.join(wa[i1:i2]))}~~")
        if op in ("insert", "replace"):
            out.append(f"**{_md(' '.join(wb[j1:j2]))}**")
        if op == "equal":
            out.append(_md(" ".join(wb[j1:j2])))
    return " ".join(out)


def _options(q: Question) -> list[str]:
    return [
        f"- {letter}) {_md(_one_line(option))}{' ✅' if i == q.answer else ''}"
        for i, (letter, option) in enumerate(zip(_LETTERS, q.options, strict=True))
    ]


def write_guide(path: Path, opposition: str, stage: Stage, cases: list[Case]) -> None:
    sheet = f"dedup_{stage.name}_review.csv"
    lines = [
        f"# Review of {stage.name} — {opposition}",
        "",
        f"Generated by `opox dedup extract {stage.name}`; do not edit. {len(cases)} case(s):",
        f"members with similarity ≥ {stage.threshold:.0f}%, directly or chained.",
        "",
        f"Fill in `group` in `{sheet}`, one row per member: members that are the same",
        "share a label (`1`, `2`...); a different one gets its own. Labels are global to",
        "the sheet and cannot span several cases.",
        "",
    ]
    if stage.name == "answers":
        lines += ["Judge the answers blind, by their meaning, without the stems.", ""]
    else:
        lines += [
            "Each case lies within one answer group. The canonical question is the most",
            "recent one; each case shows it as if all its members were joined.",
            "",
        ]
    lines += [
        "Each member shows its most recent question; diffs against A: ~~removed~~,",
        "**added**.",
        "",
    ]

    for case_id, case in zip(case_ids(cases), cases, strict=True):
        pairs = ", ".join(
            f"{member_letter(i)}–{member_letter(j)} {s:.0f}%"
            for (i, j), s in case.similarities.items()
        )
        lines += [f"## {case_id} — {pairs}", ""]
        reps = [canonical(m.questions) for m in case.members]
        if stage.name == "stems":
            top = canonical(reps)
            letter = member_letter(reps.index(top))
            lines += [
                f"Answer: `{_one_line(top.options[top.answer])}` · "  # type: ignore[index]
                f"Canonical if joined: `{top.question_id}` ({letter})",
                "",
            ]
        first = stage.text(reps[0])
        for i, (m, q) in enumerate(zip(case.members, reps, strict=True)):
            ids = ", ".join(f"`{x.question_id}`" for x in m.questions)
            text = _md(_one_line(first)) if i == 0 else word_diff(first, stage.text(q))
            lines += [f"**{member_letter(i)}** · {ids}", "", f"> {text}", ""]
            if stage.name == "stems":
                lines += [*_options(q), ""]

    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text("\n".join(lines), encoding="utf-8")
