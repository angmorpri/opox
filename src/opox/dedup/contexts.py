"""`opox dedup extract | add | check contexts`, third deduplication stage (D011).

Inputs, for a given opposition: `processed/<opposition>/questions.json` and
`interim/<opposition>/dedup_stems.json`.

Outputs, in `interim/<opposition>/`:
- `dedup_contexts.json`: the stems groups (`DedupCollection`), split where their context
  crops differ.
- `dedup_contexts_review.csv`: review sheet, one row per pair of crops found together in
  a stems group: `context_a;context_b;same;groups`. Only `same` is filled in by hand:
  `y`, `n` or blank (pending, kept as the same context).
- `dedup_contexts_review.md`: review guide with both crops of each pair.

A pair marked `n` splits every group that holds it, one subgroup per context; questions
without context stay with the most recent context.
"""

import csv
import logging
from collections import defaultdict
from collections.abc import Iterable
from dataclasses import dataclass, field
from itertools import combinations
from pathlib import Path, PurePosixPath

from opox.dedup.commands import DedupPaths, read_collection, write_collection
from opox.dedup.core import Member, answered, canonical, make_collection
from opox.models.dedup import DedupCollection
from opox.models.questions import ExamCollection, Question

COLUMNS = ["context_a", "context_b", "same", "groups"]
DECISIONS = {"y", "n", ""}

log = logging.getLogger(__name__)

type Pair = tuple[str, str]


def group_context(questions: Iterable[Question]) -> PurePosixPath | None:
    """Context of a group: that of its most recent question with context, if any."""
    with_context = [q for q in questions if q.context is not None]
    return canonical(with_context).context if with_context else None


@dataclass(frozen=True)
class Inputs:
    questions: dict[str, Question]  # answered questions by id
    stems: DedupCollection
    pairs: dict[Pair, list[str]]  # crop pairs, with the canonicals of their groups


def load_inputs(paths: DedupPaths) -> tuple[Inputs | None, list[str]]:
    if not paths.questions.is_file():
        return None, [f"file not found: {paths.questions}"]
    exams = ExamCollection.model_validate_json(paths.questions.read_text(encoding="utf-8"))
    questions = {q.question_id: q for q in answered(exams)}
    stems, error = read_collection(paths.stems)
    if error:
        return None, [error, "run the stems stage first"]
    assert stems is not None
    if {s for g in stems.root for s in g.sources} != set(questions):
        return None, [
            f"{paths.stems} does not cover the answered questions of {paths.questions}",
            "repeat the stems stage (`opox dedup check stems`)",
        ]
    pairs: dict[Pair, list[str]] = defaultdict(list)
    for g in stems.root:
        crops = sorted({str(c) for s in g.sources if (c := questions[s].context)})
        for pair in combinations(crops, 2):
            pairs[pair].append(g.canonical)
    log.info("%d stems group(s), %d crop pair(s) to review", len(stems.root), len(pairs))
    return Inputs(questions, stems, dict(sorted(pairs.items()))), []


# --- Sheet and guide ---------------------------------------------------------------------


@dataclass(frozen=True)
class Row:
    line: int
    pair: Pair
    same: str


def read_sheet(path: Path) -> tuple[list[Row], list[str]]:
    with path.open(encoding="utf-8-sig", newline="") as f:
        reader = csv.DictReader(f, delimiter=";")
        if reader.fieldnames != COLUMNS:
            return [], [f"{path}: columns must be {';'.join(COLUMNS)}"]
        return [
            Row(
                reader.line_num,
                tuple(sorted(((r["context_a"] or "").strip(), (r["context_b"] or "").strip()))),
                (r["same"] or "").strip().lower(),
            )
            for r in reader
        ], []


def write_sheet(path: Path, inputs: Inputs, decisions: dict[Pair, str]) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    with path.open("w", encoding="utf-8-sig", newline="") as f:
        writer = csv.writer(f, delimiter=";")
        writer.writerow(COLUMNS)
        for (a, b), groups in inputs.pairs.items():
            writer.writerow([a, b, decisions.get((a, b), ""), ", ".join(groups)])


def write_guide(path: Path, opposition: str, inputs: Inputs) -> None:
    by_canonical = {g.canonical: g for g in inputs.stems.root}
    width = max(2, len(str(len(inputs.pairs))))
    lines = [
        f"# Review of contexts — {opposition}",
        "",
        f"Generated by `opox dedup extract contexts`; do not edit. {len(inputs.pairs)} pair(s)",
        "of context crops found together in a stems group.",
        "",
        "Fill in `same` in `dedup_contexts_review.csv`: `y` if both crops are the same",
        "context, `n` otherwise. A pair marked `n` splits every group listed; questions",
        "without context stay with the most recent context.",
        "",
    ]
    for n, ((a, b), groups) in enumerate(inputs.pairs.items(), 1):
        lines += [f"## P{n:0{width}d} — `{a}` ↔ `{b}`", ""]
        for canonical_id in groups:
            text = inputs.questions[canonical_id].text
            ids = ", ".join(f"`{s}`" for s in by_canonical[canonical_id].sources)
            lines.append(f"- {ids}: {' '.join(text.split())}")
        image = f"../../processed/{opposition}"
        lines += ["", f"![{a}]({image}/{a}) ![{b}]({image}/{b})", ""]
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text("\n".join(lines), encoding="utf-8")


# --- Resolution --------------------------------------------------------------------------


@dataclass
class Resolution:
    collection: DedupCollection | None  # None if there are errors
    pending: int = 0
    stale: list[str] = field(default_factory=list)  # rows of pairs no longer found
    missing: list[str] = field(default_factory=list)  # pairs without row
    errors: list[str] = field(default_factory=list)


def resolve(inputs: Inputs, rows: list[Row]) -> Resolution:
    """Split the stems groups whose crops are marked as different."""
    res = Resolution(None)
    decisions: dict[Pair, str] = {}
    lines: dict[Pair, int] = {}
    for row in rows:
        if row.same not in DECISIONS:
            res.errors.append(f"line {row.line}: same must be y, n or blank, got {row.same!r}")
        elif row.pair in lines:
            res.errors.append(f"line {row.line}: pair repeated (line {lines[row.pair]})")
        elif row.pair not in inputs.pairs:
            res.stale.append(f"line {row.line}: pair not found in any group: {', '.join(row.pair)}")
        else:
            lines[row.pair] = row.line
            decisions[row.pair] = row.same
            res.pending += row.same == ""
    res.missing = [", ".join(p) for p in inputs.pairs if p not in decisions]

    parent: dict[str, str] = {}

    def find(c: str) -> str:
        while parent.setdefault(c, c) != c:
            c = parent[c]
        return c

    for pair in inputs.pairs:
        if decisions.get(pair) != "n":
            parent[find(pair[0])] = find(pair[1])
    res.errors += [
        f"line {lines[p]}: marked n, but joined through other pairs"
        for p, d in decisions.items()
        if d == "n" and find(p[0]) == find(p[1])
    ]
    if res.errors:
        return res

    groups: list[list[Member]] = []
    for g in inputs.stems.root:
        qs = [inputs.questions[s] for s in g.sources]
        with_context = [q for q in qs if q.context is not None]
        classes = {find(str(q.context)) for q in with_context}
        subgroups = [g.sources]
        if len(classes) > 1:
            top = find(str(group_context(with_context)))
            by_class: dict[str, list[str]] = defaultdict(list)
            for q in qs:
                by_class[find(str(q.context)) if q.context else top].append(q.question_id)
            subgroups = list(by_class.values())
        for ids in map(set, subgroups):
            members = [
                Member(m.key, 0, tuple(inputs.questions[s] for s in m.sources if s in ids))
                for m in g.members
            ]
            groups.append([m for m in members if m.questions])
    res.collection = make_collection(groups)
    return res


# --- Commands ----------------------------------------------------------------------------


def _summary(res: Resolution, paths: DedupPaths) -> list[str]:
    notes = [f"WARNING {paths.sheet.name} {s}" for s in res.stale]
    notes += [f"WARNING pair missing from {paths.sheet.name}: {m}" for m in res.missing]
    if res.stale or res.missing:
        notes.append("regenerate the sheet with `opox dedup extract contexts --force`")
    if res.pending:
        notes.append(f"{res.pending} pair(s) pending review in {paths.sheet}")
    return notes


def extract(
    data_dir: Path, opposition: str, stage_name: str = "contexts", force: bool = False
) -> tuple[bool, list[str]]:
    """Write the sheet, the guide and the groups. Return (success, notes)."""
    paths = DedupPaths.of(data_dir, opposition, stage_name)
    inputs, errors = load_inputs(paths)
    if errors:
        return False, errors
    assert inputs is not None

    existing = [p for p in (paths.json, paths.sheet) if p.exists()]
    if existing and not force:
        return False, [f"{p} already exists" for p in existing] + [
            "use --force to regenerate them, keeping the decisions of existing pairs"
        ]
    decisions: dict[Pair, str] = {}
    if paths.sheet.exists():
        old_rows, errors = read_sheet(paths.sheet)
        if errors:
            return False, [*errors, "fix or remove the sheet and retry"]
        decisions = {r.pair: r.same for r in old_rows if r.same}

    notes = [f"overwriting {p}" for p in existing]
    notes += [
        f"decision lost: {', '.join(p)} ({d!r})"
        for p, d in decisions.items()
        if p not in inputs.pairs
    ]
    write_sheet(paths.sheet, inputs, decisions)
    write_guide(paths.guide, opposition, inputs)
    kept = sum(p in inputs.pairs for p in decisions)
    notes.append(
        f"{len(inputs.pairs)} pair(s), {kept} decision(s) kept -> {paths.sheet}, {paths.guide}"
    )

    res = resolve(inputs, read_sheet(paths.sheet)[0])
    if res.errors:
        return False, [*notes, *res.errors, "fix the sheet and run `opox dedup add contexts`"]
    assert res.collection is not None
    write_collection(paths.json, res.collection)
    notes.append(f"{len(res.collection.root)} group(s) written to {paths.json}")
    return True, notes + _summary(res, paths)


def add(data_dir: Path, opposition: str, stage_name: str = "contexts") -> tuple[bool, list[str]]:
    """Rebuild the groups from the sheet. Return (success, notes)."""
    paths = DedupPaths.of(data_dir, opposition, stage_name)
    inputs, errors = load_inputs(paths)
    if errors:
        return False, errors
    assert inputs is not None
    if not paths.sheet.is_file():
        return False, [f"file not found: {paths.sheet}", "run `opox dedup extract contexts`"]
    rows, errors = read_sheet(paths.sheet)
    if errors:
        return False, errors

    res = resolve(inputs, rows)
    if res.errors:
        return False, [*res.errors, "fix the sheet and retry"]
    assert res.collection is not None
    current, _ = read_collection(paths.json)
    if current == res.collection:
        notes = [f"{paths.json} already up to date"]
    else:
        write_collection(paths.json, res.collection)
        notes = [f"{len(res.collection.root)} group(s) written to {paths.json}"]
    return True, notes + _summary(res, paths)


def check(data_dir: Path, opposition: str, stage_name: str = "contexts") -> list[str]:
    """Return the problems of the stage; empty if it is complete and consistent. Read-only."""
    paths = DedupPaths.of(data_dir, opposition, stage_name)
    inputs, errors = load_inputs(paths)
    if errors:
        return errors
    assert inputs is not None
    collection, error = read_collection(paths.json)
    if error:
        return [error]
    assert collection is not None

    sources = {s for g in collection.root for s in g.sources}
    errors += [f"answered question not in any group: {q}" for q in set(inputs.questions) - sources]
    errors += [
        f"unknown or unanswered question in a group: {q}" for q in sources - set(inputs.questions)
    ]

    if not paths.sheet.is_file():
        return [*errors, f"file not found: {paths.sheet}"]
    rows, sheet_errors = read_sheet(paths.sheet)
    if sheet_errors:
        return errors + sheet_errors
    res = resolve(inputs, rows)
    errors += res.errors
    errors += [f"{paths.sheet.name} {s}" for s in res.stale]
    errors += [f"pair missing from {paths.sheet.name}: {m}" for m in res.missing]
    if res.pending:
        errors.append(f"{res.pending} pair(s) pending review in {paths.sheet}")
    if res.collection is not None and res.collection != collection:
        errors.append(f"{paths.json} differs from the sheet; run `opox dedup add contexts`")
    return errors
